export function emitHostMethodDtos(
  ir: HostLibraryIr,
  ns: string = generatedNamespace(ir),
): string {
  const classes: string[] = [];
  const seen = new Set<string>();

  const addClass = (
    modelName: string,
    fields: ScalarFieldIr[],
    listFields: ListFieldIr[],
  ): void => {
    if (seen.has(modelName)) {
      return;
    }
    seen.add(modelName);
    const lines = [`    public class ${modelName}`, "    {"];
    for (const field of fields) {
      lines.push(
        `        public ${propertyType(field)} ${pascalCase(field.propertyName)} { get; set; }`,
      );
    }
    for (const listField of listFields) {
      const item = listField.itemModelName;
      lines.push(
        `        public List<${item}> ${pascalCase(listField.propertyName)} { get; set; } = new List<${item}>();`,
      );
    }
    lines.push("    }");
    classes.push(lines.join("\n"));
  };

  const addShape = (shape: ObjectShapeIr): void => {
    addClass(shape.modelName, shape.fields, shape.listFields);
    for (const listField of shape.listFields) {
      addClass(listField.itemModelName, listField.itemFields, []);
    }
  };

  for (const method of ir.methods) {
    addShape(method.input);
    addShape(method.result);
  }

  const usesLists = ir.methods.some(
    (m) => m.input.listFields.length > 0 || m.result.listFields.length > 0,
  );
  const head = usesLists
    ? [HEADER, "", "using System.Collections.Generic;", ""]
    : [HEADER, ""];
  return [
    ...head,
    `namespace ${ns}`,
    "{",
    classes.join("\n\n"),
    "}",
    "",
  ].join("\n");
}

