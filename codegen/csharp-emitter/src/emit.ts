export function emitHostDefinition(ir: HostLibraryIr): string {
  const naming = ir.naming;
  const columns = ir.columns;
  return [
    HEADER,
    "",
    "using SqliteHost;",
    "",
    `namespace ${generatedNamespace(ir)}`,
    "{",
    "    public static class GeneratedHostDefinition",
    "    {",
    "        public static SqliteHostDefinition<IGeneratedHostHandlers> Build()",
    "        {",
    "            return SqliteHostDefinition",
    "                .ForHandlers<IGeneratedHostHandlers>()",
    `                .ApiLevel(${ir.library.apiLevel})`,
    `                .MinSqliteVersion(${ir.library.minSqliteVersionNumber})`,
    "                .Naming(n => n",
    `                    .CallTablePrefix(${csharpString(naming.callTablePrefix)})`,
    `                    .ResultTablePrefix(${csharpString(naming.resultTablePrefix)})`,
    `                    .InputColumnPrefix(${csharpString(naming.inputColumnPrefix)})`,
    `                    .ResultColumnPrefix(${csharpString(naming.resultColumnPrefix)})`,
    `                    .InputListTableInfix(${csharpString(naming.inputListTableInfix)})`,
    `                    .ResultListTableInfix(${csharpString(naming.resultListTableInfix)})`,
    `                    .QueueTable(${csharpString(ir.queueTable.name)})`,
    `                    .InputsTable(${csharpString(ir.inputsTable.name)})`,
    `                    .VarsTable(${csharpString(ir.varsTable.name)})`,
    `                    .ControlTable(${csharpString(ir.controlTable.name)}))`,
    // All fourteen column values are always emitted explicitly, in
    // SqliteHostColumns property order (docs/csharp-api.md).
    "                .Columns(c => c",
    `                    .CallId(${csharpString(columns.callId)})`,
    `                    .ItemIndex(${csharpString(columns.itemIndex)})`,
    `                    .Status(${csharpString(columns.status)})`,
    `                    .DoneValue(${csharpString(columns.doneValue)})`,
    `                    .QueueId(${csharpString(columns.queueId)})`,
    `                    .Method(${csharpString(columns.method)})`,
    `                    .Name(${csharpString(columns.name)})`,
    `                    .ValueType(${csharpString(columns.valueType)})`,
    `                    .IntValue(${csharpString(columns.intValue)})`,
    `                    .RealValue(${csharpString(columns.realValue)})`,
    `                    .TextValue(${csharpString(columns.textValue)})`,
    `                    .BlobValue(${csharpString(columns.blobValue)})`,
    `                    .Action(${csharpString(columns.action)})`,
    `                    .Message(${csharpString(columns.message)}))`,
    "                .Methods(GeneratedHostMethodSpecs.BuildAll());",
    "        }",
    "    }",
    "}",
    "",
  ].join("\n");
}

// ---------------------------------------------------------------------------
// GeneratedSchemaSql.g.cs
// ---------------------------------------------------------------------------

export function emitSchemaSql(ir: HostLibraryIr): string {
  const script = generateSchemaScript(ir);
  const scriptLines = script.split("\n");
  // generateSchemaScript output ends with "\n"; drop the empty tail.
  scriptLines.pop();
  const segments = scriptLines.map((line) => csharpString(`${line}\n`));
  const literal = segments.map((segment, i) =>
    i === 0 ? `            ${segment}` : `            + ${segment}`,
  );
  literal[literal.length - 1] += ";";
  return [
    HEADER,
    "",
    `namespace ${generatedNamespace(ir)}`,
    "{",
    "    public static class GeneratedSchemaSql",
    "    {",
    "        public const string SchemaScript =",
    ...literal,
    "    }",
    "}",
    "",
  ].join("\n");
}

// ---------------------------------------------------------------------------
// ScriptEnvelope.g.cs (protocol v1, app-independent, vendored)
// ---------------------------------------------------------------------------

export function emitScriptEnvelope(): string {
  return [
    HEADER,
    "",
    "using System.Collections.Generic;",
    "",
    "namespace SqliteHost",
    "{",
    "    public class SqliteHostScript",
    "    {",
    "        public string Engine { get; set; }",
    "        public string ScriptId { get; set; }",
    "        public int RequiredApiLevel { get; set; }",
    "        public List<string> RequiredFeatures { get; set; }",
    "        public List<string> RequiredMethods { get; set; }",
    "        public List<SqliteHostRuntimeInput> Inputs { get; set; }",
    "        public List<SqliteHostStep> Steps { get; set; }",
    "    }",
    "",
    "    public class SqliteHostRuntimeInput",
    "    {",
    "        public string Name { get; set; }",
    "        public SqliteHostBindingValue Value { get; set; }",
    "    }",
    "",
    "    public class SqliteHostStep",
    "    {",
    "        public string Id { get; set; }",
    "        public List<SqliteHostStatement> Statements { get; set; }",
    "    }",
    "",
    "    public class SqliteHostStatement",
    "    {",
    "        public string Sql { get; set; }",
    "        public Dictionary<string, SqliteHostBindingValue> Bindings { get; set; }",
    "    }",
    "}",
    "",
  ].join("\n");
}

